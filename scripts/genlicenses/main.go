// genlicenses 重新生成 NOTICE 和 THIRD_PARTY_LICENSES.md。
//
// 它会编译 cftunnel，从二进制的 build info 里读出实际链接的模块
// （已应用 replace），再到 GOMODCACHE 中查找各模块的 LICENSE / NOTICE 文件。
//
// 用法（在仓库根目录执行）: go run ./scripts/genlicenses
package main

import (
	"bytes"
	"debug/buildinfo"
	"fmt"
	"log"
	"os"
	"os/exec"
	"path/filepath"
	"regexp"
	"sort"
	"strings"
)

const noticeHeader = `cftunnel_wrap
Copyright 2026 yulei666

This product is licensed under the Apache License, Version 2.0 (see LICENSE).

This product includes and statically links cloudflared
(https://github.com/cloudflare/cloudflared), Copyright Cloudflare, Inc.,
licensed under the Apache License, Version 2.0. cloudflared is used
unmodified as a Go module dependency.

Binary distributions of this product also contain third-party Go modules
under their own licenses; see THIRD_PARTY_LICENSES.md for the full list.

The NOTICE files of Apache-2.0 licensed dependencies are reproduced below,
as required by Section 4(d) of the Apache License, Version 2.0.
`

const thirdPartyHeader = "# Third-Party Licenses\n\n" +
	"`cftunnel` statically links the Go modules below. This list was generated by\n" +
	"`go run ./scripts/genlicenses` from the build info of the compiled binary.\n" +
	"License types were identified from each module's LICENSE file. The full license\n" +
	"texts ship with each module's source; run `go mod download` and look in\n" +
	"`$(go env GOMODCACHE)`.\n\n" +
	"The Go standard library is distributed under the BSD-3-Clause license\n" +
	"(https://go.dev/LICENSE).\n\n" +
	"| Module | Version | License |\n|---|---|---|\n"

var (
	licenseFile = regexp.MustCompile(`(?i)^(licen[cs]e|copying)`)
	noticeFile  = regexp.MustCompile(`^NOTICE`)
)

func main() {
	log.SetFlags(0)

	tmp, err := os.MkdirTemp("", "genlicenses")
	if err != nil {
		log.Fatal(err)
	}
	defer os.RemoveAll(tmp)
	bin := filepath.Join(tmp, "cftunnel")
	run("go", "build", "-trimpath", "-o", bin, ".")

	info, err := buildinfo.ReadFile(bin)
	if err != nil {
		log.Fatal(err)
	}
	modCache := strings.TrimSpace(run("go", "env", "GOMODCACHE"))

	var notice, table bytes.Buffer
	notice.WriteString(noticeHeader)
	table.WriteString(thirdPartyHeader)

	unknown := 0
	for _, dep := range info.Deps {
		src := dep
		if dep.Replace != nil {
			src = dep.Replace
		}
		dir := filepath.Join(modCache, escape(src.Path)+"@"+escape(src.Version))

		licenses := map[string]bool{}
		for _, f := range matchFiles(dir, licenseFile) {
			licenses[classify(readFile(f))] = true
		}
		lic := joinKeys(licenses)
		if lic == "" || licenses["UNKNOWN"] {
			unknown++
			if lic == "" {
				lic = "NOFILE"
			}
		}

		name := dep.Path
		if dep.Replace != nil {
			name += " (=> " + dep.Replace.Path + ")"
		}
		fmt.Fprintf(&table, "| `%s` | %s | %s |\n", name, src.Version, lic)

		for _, f := range matchFiles(dir, noticeFile) {
			fmt.Fprintf(&notice, "\n%s\n%s@%s\n%s\n%s",
				strings.Repeat("=", 80), src.Path, src.Version, strings.Repeat("=", 80), readFile(f))
		}
	}

	write("NOTICE", notice.Bytes())
	write("THIRD_PARTY_LICENSES.md", table.Bytes())
	log.Printf("wrote NOTICE and THIRD_PARTY_LICENSES.md (%d modules)", len(info.Deps))
	if unknown > 0 {
		log.Fatalf("%d module(s) have an unrecognized or missing license; review THIRD_PARTY_LICENSES.md", unknown)
	}
}

// classify 根据 LICENSE 文本中的特征语句判断许可证类型。
func classify(text string) string {
	if len(text) > 4000 {
		text = text[:4000]
	}
	has := func(s string) bool { return strings.Contains(text, s) }
	switch {
	case has("Apache License") && has("Version 2.0"):
		return "Apache-2.0"
	case has("Mozilla Public License"):
		return "MPL-2.0"
	case has("ISC License"), has("Permission to use, copy, modify, and/or distribute"):
		return "ISC"
	case has("Permission is hereby granted, free of charge"):
		return "MIT"
	case has("Redistribution and use in source and binary forms"):
		if has("Neither the name") || has("names of its") || has("name of the copyright holder") {
			return "BSD-3-Clause"
		}
		return "BSD-2-Clause"
	}
	return "UNKNOWN"
}

// escape 按 module cache 的规则把大写字母转成 "!" + 小写。
func escape(s string) string {
	var b strings.Builder
	for _, r := range s {
		if 'A' <= r && r <= 'Z' {
			b.WriteByte('!')
			r += 'a' - 'A'
		}
		b.WriteRune(r)
	}
	return b.String()
}

func matchFiles(dir string, re *regexp.Regexp) []string {
	entries, err := os.ReadDir(dir)
	if err != nil {
		log.Fatalf("%s: %v (run `go mod download` first)", dir, err)
	}
	var out []string
	for _, e := range entries {
		if !e.IsDir() && re.MatchString(e.Name()) {
			out = append(out, filepath.Join(dir, e.Name()))
		}
	}
	return out
}

func joinKeys(m map[string]bool) string {
	keys := make([]string, 0, len(m))
	for k := range m {
		keys = append(keys, k)
	}
	sort.Strings(keys)
	return strings.Join(keys, " + ")
}

func readFile(path string) string {
	data, err := os.ReadFile(path)
	if err != nil {
		log.Fatal(err)
	}
	return string(data)
}

func write(path string, data []byte) {
	if err := os.WriteFile(path, data, 0o644); err != nil {
		log.Fatal(err)
	}
}

func run(name string, args ...string) string {
	cmd := exec.Command(name, args...)
	cmd.Stderr = os.Stderr
	out, err := cmd.Output()
	if err != nil {
		log.Fatalf("%s %s: %v", name, strings.Join(args, " "), err)
	}
	return string(out)
}
